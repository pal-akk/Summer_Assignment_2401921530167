package theproject;

public class Point {
	private int x;
	private int y;
	public Point() {
		
	}
	public Point(int x , int y) {
		this.x = x;
	}
	public void setX(int x) {
		this.x = x;
		
	}
	public void setY(int y) {
		this.x = x;
		
	}
	public void setXY(int x , int y) {
		this.x = x;
		this.y = y;
		
	}

}
